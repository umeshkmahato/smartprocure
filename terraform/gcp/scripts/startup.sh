#!/bin/bash
# =============================================================================
# SmartProcure — GCP VM Startup Script
# =============================================================================
# This script runs ONCE automatically when your GCP VM first boots.
# It installs Docker and starts all SmartProcure infrastructure services.
#
# Variables like ${db_password} are replaced by Terraform before the script
# is uploaded to GCP metadata — you don't need to edit anything here.
#
# To watch this script run in real time (after SSH):
#   sudo journalctl -u google-startup-scripts -f
# =============================================================================

set -euo pipefail  # stop on any error, treat unset vars as errors

# Log all output with timestamps
exec > >(while IFS= read -r line; do echo "$(date '+%Y-%m-%d %H:%M:%S') $line"; done | tee /var/log/startup.log) 2>&1

echo "=============================================="
echo " SmartProcure — GCP VM Startup"
echo " Started at: $(date)"
echo " Machine: $(curl -s -H 'Metadata-Flavor: Google' http://metadata.google.internal/computeMetadata/v1/instance/machine-type | awk -F/ '{print $NF}')"
echo "=============================================="

# ── STEP 1: Update system packages ───────────────────────────────────────────
echo ""
echo "[ 1/6 ] Updating system packages..."
export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get upgrade -y -o Dpkg::Options::="--force-confdef" -o Dpkg::Options::="--force-confold"

# ── STEP 2: Install Docker ────────────────────────────────────────────────────
echo ""
echo "[ 2/6 ] Installing Docker..."

apt-get install -y \
  ca-certificates \
  curl \
  gnupg \
  git \
  wget \
  unzip \
  netcat-openbsd \
  htop

# Add Docker's official GPG key
install -m 0755 -d /etc/apt/keyrings
curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
chmod a+r /etc/apt/keyrings/docker.asc

# Add the Docker repository
echo \
  "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] \
  https://download.docker.com/linux/ubuntu \
  $(. /etc/os-release && echo "$VERSION_CODENAME") stable" | \
  tee /etc/apt/sources.list.d/docker.list > /dev/null

# Install Docker Engine + Compose plugin
apt-get update -y
apt-get install -y \
  docker-ce \
  docker-ce-cli \
  containerd.io \
  docker-buildx-plugin \
  docker-compose-plugin

# Start Docker and make it auto-start on reboot
systemctl start docker
systemctl enable docker

# Allow the app user to run docker without sudo
# GCP creates the ssh_username on first SSH — we pre-create it here
useradd -m -s /bin/bash ${project_name} 2>/dev/null || true
usermod -aG docker ${project_name}
usermod -aG docker $(logname 2>/dev/null || echo "root")

echo "✅ Docker: $(docker --version)"
echo "✅ Docker Compose: $(docker compose version)"

# ── STEP 3: Create application directory ─────────────────────────────────────
echo ""
echo "[ 3/6 ] Creating application directory..."

mkdir -p /opt/smartprocure
cd /opt/smartprocure

# ── STEP 4: Write .env file ───────────────────────────────────────────────────
# Terraform substitutes ${variable} placeholders below before uploading.
echo ""
echo "[ 4/6 ] Writing .env configuration..."

cat > /opt/smartprocure/.env << 'ENVEOF'
# SmartProcure Environment Configuration
# Generated by Terraform on first boot (GCP)

# ── Spring ──────────────────────────────
SPRING_PROFILES_ACTIVE=dev

# ── Database ────────────────────────────
DB_URL=jdbc:postgresql://sp-postgres:5432/smartprocure
DB_USERNAME=PLACEHOLDER_DB_USERNAME
DB_PASSWORD=PLACEHOLDER_DB_PASSWORD
DB_PORT=5432
DB_POOL_MAX=10
DB_POOL_MIN=2

# ── Redis ───────────────────────────────
REDIS_HOST=sp-redis
REDIS_PORT=6379
REDIS_PASSWORD=

# ── Kafka ───────────────────────────────
KAFKA_BOOTSTRAP_SERVERS=sp-kafka:29092
KAFKA_CONSUMER_GROUP=sp-main-group
KAFKA_PORT=9092

# ── JWT ─────────────────────────────────
JWT_SECRET=PLACEHOLDER_JWT_SECRET
JWT_ACCESS_EXPIRY=900
JWT_REFRESH_EXPIRY=604800

# ── CORS ────────────────────────────────
CORS_ALLOWED_ORIGINS=*

# ── Mail (MailHog for dev) ───────────────
MAIL_HOST=sp-mailhog
MAIL_PORT=1025
MAIL_USERNAME=
MAIL_PASSWORD=
MAIL_AUTH=false
MAIL_TLS=false

# ── Admin ───────────────────────────────
ADMIN_EMAIL=PLACEHOLDER_ADMIN_EMAIL
ADMIN_PASSWORD=PLACEHOLDER_ADMIN_PASSWORD

# ── File Upload ─────────────────────────
MAX_FILE_SIZE=10MB
MAX_REQUEST_SIZE=10MB
SERVER_PORT=8080

# ── Notification Service ────────────────
NOTIFICATION_SERVICE_PORT=8081
NOTIFICATION_KAFKA_GROUP=sp-notification-group
NOTIFICATION_FROM_ADDRESS=no-reply@smartprocure.internal
ENVEOF

# Substitute actual Terraform values into placeholders
sed -i "s|PLACEHOLDER_DB_USERNAME|${db_username}|g"       /opt/smartprocure/.env
sed -i "s|PLACEHOLDER_DB_PASSWORD|${db_password}|g"       /opt/smartprocure/.env
sed -i "s|PLACEHOLDER_JWT_SECRET|${jwt_secret}|g"         /opt/smartprocure/.env
sed -i "s|PLACEHOLDER_ADMIN_EMAIL|${admin_email}|g"       /opt/smartprocure/.env
sed -i "s|PLACEHOLDER_ADMIN_PASSWORD|${admin_password}|g" /opt/smartprocure/.env

echo "✅ .env written"

# ── STEP 5: Write docker-compose.yml ─────────────────────────────────────────
# Single-quoted 'COMPOSEEOF' means bash will NOT expand $ signs inside —
# Docker Compose $${VAR} syntax stays as-is in the file.
echo ""
echo "[ 5/6 ] Writing docker-compose.yml..."

cat > /opt/smartprocure/docker-compose.yml << 'COMPOSEEOF'
version: '3.8'

# ============================================================
# SmartProcure — Infrastructure Services
# All application services share this network.
# ============================================================

networks:
  sp-network:
    driver: bridge
    name: sp-network

volumes:
  postgres-data:
  redis-data:
  zookeeper-data:
  zookeeper-log:
  kafka-data:

services:

  # ── PostgreSQL with pgvector extension ──────────────────────
  sp-postgres:
    image: pgvector/pgvector:pg16
    container_name: sp-postgres
    restart: unless-stopped
    ports:
      - "5432:5432"
    environment:
      POSTGRES_DB: smartprocure
      POSTGRES_USER: $${DB_USERNAME:-smartprocure}
      POSTGRES_PASSWORD: $${DB_PASSWORD:-smartprocure_dev}
    volumes:
      - postgres-data:/var/lib/postgresql/data
    networks:
      - sp-network
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U $${DB_USERNAME:-smartprocure} -d smartprocure"]
      interval: 10s
      timeout: 5s
      retries: 5
      start_period: 20s

  # ── Redis (session & cache) ──────────────────────────────────
  sp-redis:
    image: redis:7.4-alpine
    container_name: sp-redis
    restart: unless-stopped
    command: >
      redis-server
      --maxmemory 128mb
      --maxmemory-policy allkeys-lru
      --appendonly yes
    ports:
      - "6379:6379"
    volumes:
      - redis-data:/data
    networks:
      - sp-network
    healthcheck:
      test: ["CMD", "redis-cli", "ping"]
      interval: 10s
      timeout: 5s
      retries: 5

  # ── Zookeeper (required by Kafka) ────────────────────────────
  sp-zookeeper:
    image: confluentinc/cp-zookeeper:7.7.1
    container_name: sp-zookeeper
    restart: unless-stopped
    ports:
      - "2181:2181"
    environment:
      ZOOKEEPER_CLIENT_PORT: 2181
      ZOOKEEPER_TICK_TIME: 2000
      ZOOKEEPER_LOG4J_ROOT_LOGLEVEL: WARN
    volumes:
      - zookeeper-data:/var/lib/zookeeper/data
      - zookeeper-log:/var/lib/zookeeper/log
    networks:
      - sp-network
    healthcheck:
      test: ["CMD-SHELL", "echo ruok | nc -w 2 localhost 2181 | grep imok"]
      interval: 10s
      timeout: 5s
      retries: 5
      start_period: 15s

  # ── Kafka (message broker) ────────────────────────────────────
  # NOTE: On e2-micro (1 GB RAM) Kafka + Zookeeper uses ~600 MB.
  # If the VM runs out of memory, upgrade to e2-small (~$7/mo).
  sp-kafka:
    image: confluentinc/cp-kafka:7.7.1
    container_name: sp-kafka
    restart: unless-stopped
    depends_on:
      sp-zookeeper:
        condition: service_healthy
    ports:
      - "9092:9092"
    environment:
      KAFKA_BROKER_ID: 1
      KAFKA_ZOOKEEPER_CONNECT: sp-zookeeper:2181
      KAFKA_LISTENER_SECURITY_PROTOCOL_MAP: PLAINTEXT:PLAINTEXT,INTERNAL:PLAINTEXT
      KAFKA_ADVERTISED_LISTENERS: PLAINTEXT://localhost:9092,INTERNAL://sp-kafka:29092
      KAFKA_INTER_BROKER_LISTENER_NAME: INTERNAL
      KAFKA_OFFSETS_TOPIC_REPLICATION_FACTOR: 1
      KAFKA_TRANSACTION_STATE_LOG_REPLICATION_FACTOR: 1
      KAFKA_TRANSACTION_STATE_LOG_MIN_ISR: 1
      KAFKA_AUTO_CREATE_TOPICS_ENABLE: "true"
      KAFKA_LOG_RETENTION_HOURS: 24
      KAFKA_HEAP_OPTS: "-Xmx256M -Xms128M"
      KAFKA_LOG4J_LOGGERS: "kafka=WARN,kafka.controller=WARN,kafka.log.LogCleaner=WARN"
    volumes:
      - kafka-data:/var/lib/kafka/data
    networks:
      - sp-network
    healthcheck:
      test: ["CMD-SHELL", "nc -z localhost 9092"]
      interval: 20s
      timeout: 10s
      retries: 5
      start_period: 30s

  # ── MailHog (catches all dev emails — view at port 8025) ─────
  sp-mailhog:
    image: mailhog/mailhog:v1.0.1
    container_name: sp-mailhog
    restart: unless-stopped
    ports:
      - "1025:1025"   # SMTP — apps send email here
      - "8025:8025"   # Web UI — you view emails here
    networks:
      - sp-network

COMPOSEEOF

echo "✅ docker-compose.yml written"

# ── STEP 6: Create systemd service & start the stack ─────────────────────────
echo ""
echo "[ 6/6 ] Creating systemd service and starting the stack..."

cat > /etc/systemd/system/smartprocure.service << 'SERVICEEOF'
[Unit]
Description=SmartProcure Infrastructure Stack
Documentation=https://github.com/your-org/smartprocure
After=docker.service network-online.target
Requires=docker.service
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
WorkingDirectory=/opt/smartprocure
EnvironmentFile=/opt/smartprocure/.env
ExecStartPre=/usr/bin/docker compose pull --quiet
ExecStart=/usr/bin/docker compose up -d --remove-orphans
ExecStop=/usr/bin/docker compose down
ExecReload=/usr/bin/docker compose restart
TimeoutStartSec=300
Restart=on-failure
RestartSec=10s

[Install]
WantedBy=multi-user.target
SERVICEEOF

systemctl daemon-reload
systemctl enable smartprocure
systemctl start smartprocure

# ── Wait for services to become healthy ──────────────────────────────────────
echo ""
echo "Waiting for services to become healthy (up to 3 minutes)..."
TIMEOUT=180
ELAPSED=0
until docker compose -f /opt/smartprocure/docker-compose.yml ps | grep -q "healthy"; do
  if [ "$ELAPSED" -ge "$TIMEOUT" ]; then
    echo "⚠️  Timeout — check: docker compose ps"
    break
  fi
  sleep 10
  ELAPSED=$((ELAPSED + 10))
  echo "  ... waited $${ELAPSED}s"
done

# ── Fix directory permissions for the app user ───────────────────────────────
chown -R ${project_name}:${project_name} /opt/smartprocure 2>/dev/null || \
chown -R root:docker /opt/smartprocure

# ── Print final status ────────────────────────────────────────────────────────
echo ""
echo "=============================================="
echo " SmartProcure — Startup Complete"
echo " Finished at: $(date)"
echo "=============================================="
echo ""
echo "📋 Container status:"
docker compose -f /opt/smartprocure/docker-compose.yml ps
echo ""
echo "🌐 Services available at this VM's public IP:"
echo "   PostgreSQL  → port 5432"
echo "   Redis       → port 6379"
echo "   Kafka       → port 9092"
echo "   MailHog UI  → port 8025"
echo ""
echo "📌 Useful commands (run after SSH):"
echo "   cd /opt/smartprocure"
echo "   docker compose ps              # check status"
echo "   docker compose logs -f         # stream all logs"
echo "   docker logs sp-postgres        # postgres logs"
echo "   docker logs sp-kafka           # kafka logs"
echo ""
echo "🚀 Next: deploy the application services (see README.md)"
